// Copies API types and translations from the web app so both clients stay in sync.
// Run after changing frontend/src/lib/types.ts or frontend/src/i18n/{en,vi}.ts.
const fs = require('fs')
const path = require('path')

const web = path.join(__dirname, '..', '..', 'frontend', 'src')
const out = path.join(__dirname, '..', 'src')
const header = '// AUTO-GENERATED by scripts/sync-shared.js from frontend/src. Do not edit here.\n'

for (const [from, to] of [
  ['lib/types.ts', 'lib/types.ts'],
  ['i18n/en.ts', 'i18n/web-en.ts'],
  ['i18n/vi.ts', 'i18n/web-vi.ts'],
]) {
  fs.writeFileSync(path.join(out, to), header + fs.readFileSync(path.join(web, from), 'utf8'))
  console.log(`synced ${from} -> src/${to}`)
}
